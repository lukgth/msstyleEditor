// Generates libmsstyle/XpSchema.cs from the Windows XP tmschema.h.
// usage: dotnet run tools/XpSchemaGen.cs -- <path to tmschema.h> <output .cs>
using System.Text;
using System.Text.RegularExpressions;

if (args.Length != 2)
{
    Console.Error.WriteLine("usage: dotnet run tools/XpSchemaGen.cs -- <tmschema.h> <out.cs>");
    return 2;
}

var props = new List<(int Id, string Name, string Prim)>();
var enums = new List<(string Name, List<(int Val, string Name)> Values)>();
List<(int, string)> current = null;

var rxProp = new Regex(@"^\s*TM_PROP\(\s*(\d+)\s*,\s*\w+\s*,\s*(\w+)\s*,\s*(\w+)\s*\)");
var rxBegin = new Regex(@"^\s*BEGIN_TM_(ENUM|CLASS_PARTS|PART_STATES)\(\s*(\w+)\s*\)");
var rxVal = new Regex(@"^\s*TM_(ENUM|PART|STATE)\(\s*(\d+)\s*,\s*\w+\s*,\s*(\w+)\s*\)");
var rxEnd = new Regex(@"^\s*END_TM_(ENUM|CLASS_PARTS|PART_STATES)\(\)");

foreach (var raw in File.ReadLines(args[0]))
{
    string line = raw;
    int c = line.IndexOf("//", StringComparison.Ordinal);
    if (c >= 0) line = line.Substring(0, c);
    Match m;
    if ((m = rxProp.Match(line)).Success)
    {
        props.Add((int.Parse(m.Groups[1].Value), m.Groups[2].Value, m.Groups[3].Value));
    }
    else if ((m = rxBegin.Match(line)).Success)
    {
        string suffix = m.Groups[1].Value == "CLASS_PARTS" ? "PARTS" : m.Groups[1].Value == "PART_STATES" ? "STATES" : "";
        current = new List<(int, string)>();
        enums.Add((m.Groups[2].Value + suffix, current));
    }
    else if ((m = rxVal.Match(line)).Success)
    {
        if (current == null) throw new InvalidDataException("value outside an enum: " + raw);
        current.Add((int.Parse(m.Groups[2].Value), m.Groups[3].Value));
    }
    else if (rxEnd.IsMatch(line))
    {
        current = null;
    }
    else if (Regex.IsMatch(line, @"\bTM_(PROP|ENUM|PART|STATE)\("))
    {
        // anything the patterns above don't cover (a symbolic value...) must not be dropped silently.
        throw new InvalidDataException("unrecognized schema line: " + raw);
    }
}

var sb = new StringBuilder();
sb.AppendLine("// <auto-generated>");
sb.AppendLine("// Generated by tools/XpSchemaGen.cs from the Windows XP SP1 public/sdk/inc/tmschema.h. Do not edit.");
sb.AppendLine("// </auto-generated>");
sb.AppendLine("using System;");
sb.AppendLine("using System.Collections.Generic;");
sb.AppendLine();
sb.AppendLine("namespace libmsstyle");
sb.AppendLine("{");
sb.AppendLine("    /// <summary>Windows XP theme schema: property ids and types, enums, class parts and part states.</summary>");
sb.AppendLine("    public static class XpSchema");
sb.AppendLine("    {");
sb.AppendLine("        /// <summary>INI property name -> (TMT id, primitive type name as in tmschema.h).</summary>");
sb.AppendLine("        public static readonly Dictionary<string, (int Id, string Prim)> Properties = new Dictionary<string, (int, string)>(StringComparer.OrdinalIgnoreCase)");
sb.AppendLine("        {");
foreach (var p in props) sb.AppendLine($"            [\"{p.Name}\"] = ({p.Id}, \"{p.Prim}\"),");
sb.AppendLine("        };");
sb.AppendLine();
sb.AppendLine("        /// <summary>enum name (BGTYPE, WINDOWPARTS, CAPTIONSTATES...) -> value name -> value.</summary>");
sb.AppendLine("        public static readonly Dictionary<string, Dictionary<string, int>> Enums = new Dictionary<string, Dictionary<string, int>>(StringComparer.OrdinalIgnoreCase)");
sb.AppendLine("        {");
foreach (var e in enums)
{
    sb.AppendLine($"            [\"{e.Name}\"] = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase)");
    sb.AppendLine("            {");
    foreach (var v in e.Values) sb.AppendLine($"                [\"{v.Name}\"] = {v.Val},");
    sb.AppendLine("            },");
}
sb.AppendLine("        };");
sb.AppendLine("    }");
sb.AppendLine("}");
File.WriteAllText(args[1], sb.ToString(), new UTF8Encoding(true));
Console.WriteLine($"{props.Count} properties, {enums.Count} enums -> {args[1]}");
return 0;
